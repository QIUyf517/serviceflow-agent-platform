const TECHNICAL_VALUES = /^(?:\d+(?:\.\d+)?(?:%|GB|mAh|MP|K|L|p)?|\d+TB SSD|\d+GB SSD|A[456]|AMOLED|HEPA|i[579]|IPX[47]|LCD|PVC|RGB|TPE|USB|USB-[AC]|Wi-Fi|XS|S|M|L|XL|XXL)$/

export function productName(name: string | undefined, productId: string): string {
  if (name && PRODUCT_NAMES[name]) return PRODUCT_NAMES[name]
  if (name && /[\u3400-\u9fff]/u.test(name)) return name
  return `模拟商品 #${productId}`
}

export function optionLabel(name: string): string {
  return OPTION_LABELS[name] ?? '规格'
}

export function optionValue(value: string): string {
  const translated = OPTION_VALUES[value]
  if (translated) return translated
  if (/[\u3400-\u9fff]/u.test(value) || TECHNICAL_VALUES.test(value)) return value

  const unitPatterns: Array<[RegExp, string]> = [
    [/^(\d+(?:\.\d+)?) cups?$/, '$1 杯'],
    [/^(\d+(?:\.\d+)?) liters?$/, '$1 升'],
    [/^(\d+(?:\.\d+)?)L$/, '$1 升'],
    [/^(\d+(?:\.\d+)?) hours?$/, '$1 小时'],
    [/^(\d+(?:\.\d+)?)(?:-inch| inch(?:es)?)$/, '$1 英寸'],
    [/^(\d+(?:\.\d+)?) ?ft$/, '$1 英尺'],
    [/^(\d+)-(\d+) lbs$/, '$1–$2 磅'],
    [/^(\d+(?:\.\d+)?)ml$/, '$1 毫升'],
    [/^(\d+(?:\.\d+)?)mm$/, '$1 毫米'],
    [/^(\d+(?:\.\d+)?) bar$/, '$1 巴'],
    [/^(\d+(?:\.\d+)?) degrees$/, '$1 度'],
    [/^(\d+(?:\.\d+)?)W equivalent$/, '相当于 $1 W'],
    [/^(\d+)-piece$/, '$1 件套'],
    [/^(\d+)x$/, '$1 倍'],
  ]
  for (const [pattern, replacement] of unitPatterns) {
    if (pattern.test(value)) return value.replace(pattern, replacement)
  }
  return '规格值'
}
